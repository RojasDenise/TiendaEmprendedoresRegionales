-- =============================================
-- 5. TRIGGER: ACTUALIZACIÓN DE STOCK Y ESTADO
-- =============================================
-- Cuando se registra un Pago 'Aprobado':
--   1) descuenta del stock las cantidades de la factura pagada
--   2) pasa a 'Sin Stock' los productos que quedaron en 0
-- En PostgreSQL un trigger son dos piezas: la función y el trigger que la llama.

CREATE OR REPLACE FUNCTION fn_actualizar_stock_y_estado()
RETURNS TRIGGER AS $$
BEGIN
  IF EXISTS (
    SELECT 1
    FROM EstadoPago ep
    WHERE ep."id_estadoPago" = NEW."id_estadoPago"
      AND ep.descripcion = 'Aprobado'
  ) THEN
    UPDATE Producto p
    SET stock = p.stock - df.cantidad
    FROM DetalleFactura df
    WHERE df.id_producto = p.id_producto
      AND df.id_factura = NEW.id_factura;

    UPDATE Producto
    SET id_estado_prod = (
      SELECT id_estado_prod
      FROM Estado_Producto
      WHERE descripcion = 'Sin Stock'
    )
    WHERE stock = 0;
  END IF;

  RETURN NEW;
END;
$$ LANGUAGE plpgsql;

CREATE TRIGGER tr_ActualizarStockYEstado
AFTER INSERT ON Pago
FOR EACH ROW
EXECUTE FUNCTION fn_actualizar_stock_y_estado();
