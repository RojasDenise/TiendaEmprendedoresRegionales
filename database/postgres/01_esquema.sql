-- =====================================================================
-- Tienda Emprendedores Regionales - Esquema para PostgreSQL
-- =====================================================================
-- Migrado desde el script de SQL Server (database/TiendaEmprendedoresRegionales.sql).
--
-- Cómo correrlo:
--   psql "<DATABASE_URL>" -f database/postgres/01_esquema.sql
--   (o pegarlo en el SQL Editor de Neon)
--
-- IMPORTANTE - nombres con mayúsculas o ñ:
--   PostgreSQL pasa a minúsculas todo nombre que no esté entre comillas dobles.
--   Para que la API siga devolviendo los mismos nombres que antes
--   (DNI, nombreEmprendimiento, id_itemCarrito, etc.), esas columnas están
--   creadas entre comillas y HAY QUE ESCRIBIRLAS ENTRE COMILLAS en cada consulta:
--       SELECT "DNI", "nombreEmprendimiento" FROM Usuario      -- bien
--       SELECT DNI, nombreEmprendimiento FROM Usuario          -- error: no existe la columna
--   Las columnas en minúscula (id_producto, nombre, stock...) y los nombres de
--   tabla se escriben normal, sin comillas.
--
-- Cambios respecto de SQL Server:
--   IDENTITY(1,1)  -> GENERATED BY DEFAULT AS IDENTITY
--   FLOAT          -> DOUBLE PRECISION
--   DATETIME       -> TIMESTAMPTZ (guarda el instante exacto, con zona horaria)
--   VARCHAR(MAX)   -> TEXT
--   Valoración     -> Valoracion (tabla sin tilde)
--   Mensaje_Reclamo.imagen: el backend la usa pero faltaba en el script anterior.
--   Producto.imagen: ahora acepta NULL (el formulario permite crear sin imagen).
--   Los procedimientos sp_obtenerProductos y sp_actualizarProducto pasaron a ser
--   consultas dentro de backend/src/services/productoService.js.
-- =====================================================================


